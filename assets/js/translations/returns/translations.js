// Merge with global translations if needed
if (typeof window.translations !== 'undefined') {
    // Merge returns translations into global translations
    for (let lang in returnsTranslations) {
        if (!window.translations[lang]) {
            window.translations[lang] = {};
        }
        Object.assign(window.translations[lang], returnsTranslations[lang]);
    }
}

// Make returns translations globally available
window.returnsTranslations = returnsTranslations;

// Override t function to ensure returns translations are included
const originalT = window.t;
if (typeof window !== 'undefined' && originalT) {
    window.t = function(key) {
        const lang = window.getCurrentLanguage ? window.getCurrentLanguage() : 'en';
        
        // First check returns translations
        if (returnsTranslations[lang] && returnsTranslations[lang][key] !== undefined) {
            return returnsTranslations[lang][key];
        }
        
        // Then check global translations
        if (window.translations && window.translations[lang] && window.translations[lang][key] !== undefined) {
            return window.translations[lang][key];
        }
        
        // Fallback to English in returns translations
        if (returnsTranslations.en && returnsTranslations.en[key] !== undefined) {
            return returnsTranslations.en[key];
        }
        
        // Fallback to global English
        if (window.translations && window.translations.en && window.translations.en[key] !== undefined) {
            return window.translations.en[key];
        }
        
        console.warn(`Translation missing for key: ${key}`);
        return key;
    };
}